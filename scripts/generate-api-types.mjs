import { readFileSync, writeFileSync } from 'node:fs';
const source = new URL('../sdk/contracts.json', import.meta.url);
const target = new URL('../sdk/types/contracts.d.ts', import.meta.url);
const contracts = JSON.parse(readFileSync(source,'utf8'));
function type(schema) {
  if (schema.$ref) return schema.$ref.split('/').at(-1);
  if (schema.anyOf) return schema.anyOf.map(type).join(' | ');
  if (Object.hasOwn(schema,'const')) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(value=>JSON.stringify(value)).join(' | ');
  if (schema.type==='object') {
    if (!schema.properties) return schema.additionalProperties && typeof schema.additionalProperties==='object' ? `Record<string, ${type(schema.additionalProperties)}>` : 'Record<string, unknown>';
    return `{ ${Object.entries(schema.properties).map(([key,value])=>`${JSON.stringify(key)}${schema.required?.includes(key)?'':'?'}: ${type(value)};`).join(' ')} }`;
  }
  if (schema.type==='array') return `Array<${type(schema.items)}>`;
  return {integer:'number',number:'number',boolean:'boolean',string:'string',null:'null'}[schema.type] ?? 'unknown';
}
const result = '// Generated by scripts/generate-api-types.mjs from sdk/contracts.json.\n' + Object.entries(contracts.$defs).map(([name,schema])=>`export type ${name} = ${type(schema)};`).join('\n')+'\n';
if (process.argv.includes('--check')) {
  // Git may check text out as CRLF on Windows; that is not a schema change.
  if (readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==result) throw new Error('API declarations are stale; run node scripts/generate-api-types.mjs');
} else writeFileSync(target,result);
